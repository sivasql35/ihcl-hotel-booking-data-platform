WITH CAMPAIGN_ACTIVITY_METRICS AS (

    SELECT
        CAMPAIGN_ID,

        COUNT(CAMPAIGN_ACTIVITY_ID)
            AS TOTAL_ACTIVITIES,

        COUNT_IF(DELIVERY_STATUS = 'DELIVERED')
            AS DELIVERED_ACTIVITIES,

        COUNT_IF(DELIVERY_STATUS = 'BOUNCED')
            AS BOUNCED_ACTIVITIES,

        COUNT_IF(OPEN_DATE IS NOT NULL)
            AS OPENED_ACTIVITIES,

        COUNT_IF(CLICK_DATE IS NOT NULL)
            AS CLICKED_ACTIVITIES,

        COUNT_IF(CONVERSION_DATE IS NOT NULL)
            AS CONVERTED_ACTIVITIES,

        COUNT_IF(RESPONSE_STATUS = 'NO_RESPONSE')
            AS NO_RESPONSE_ACTIVITIES,

        SUM(CONVERSION_VALUE)
            AS TOTAL_CONVERSION_VALUE,

        SUM(CAMPAIGN_COST)
            AS TOTAL_CAMPAIGN_COST,

        AVG(CONVERSION_VALUE)
            AS AVG_CONVERSION_VALUE,

        MIN(SENT_DATE)
            AS FIRST_SENT_DATE,

        MAX(SENT_DATE)
            AS LAST_SENT_DATE

    FROM {{ ref('silver_crm_campaign_activity') }}

    GROUP BY CAMPAIGN_ID

)

SELECT
    C.CAMPAIGN_ID,
    C.CAMPAIGN_NAME,
    C.CAMPAIGN_TYPE,
    C.CHANNEL,
    C.TARGET_AUDIENCE,
    C.CAMPAIGN_START_DATE,
    C.CAMPAIGN_END_DATE,
    C.CAMPAIGN_BUDGET,
    C.CAMPAIGN_STATUS,

    COALESCE(A.TOTAL_ACTIVITIES, 0)
        AS TOTAL_ACTIVITIES,

    COALESCE(A.DELIVERED_ACTIVITIES, 0)
        AS DELIVERED_ACTIVITIES,

    COALESCE(A.BOUNCED_ACTIVITIES, 0)
        AS BOUNCED_ACTIVITIES,

    COALESCE(A.OPENED_ACTIVITIES, 0)
        AS OPENED_ACTIVITIES,

    COALESCE(A.CLICKED_ACTIVITIES, 0)
        AS CLICKED_ACTIVITIES,

    COALESCE(A.CONVERTED_ACTIVITIES, 0)
        AS CONVERTED_ACTIVITIES,

    COALESCE(A.NO_RESPONSE_ACTIVITIES, 0)
        AS NO_RESPONSE_ACTIVITIES,

    COALESCE(A.TOTAL_CONVERSION_VALUE, 0)
        AS TOTAL_CONVERSION_VALUE,

    COALESCE(A.TOTAL_CAMPAIGN_COST, 0)
        AS TOTAL_CAMPAIGN_COST,

    A.AVG_CONVERSION_VALUE,
    A.FIRST_SENT_DATE,
    A.LAST_SENT_DATE,

    ROUND(
        100.0 * COALESCE(A.DELIVERED_ACTIVITIES, 0)
        / NULLIF(A.TOTAL_ACTIVITIES, 0),
        2
    ) AS DELIVERY_RATE_PCT,

    ROUND(
        100.0 * COALESCE(A.OPENED_ACTIVITIES, 0)
        / NULLIF(A.DELIVERED_ACTIVITIES, 0),
        2
    ) AS OPEN_RATE_PCT,

    ROUND(
        100.0 * COALESCE(A.CLICKED_ACTIVITIES, 0)
        / NULLIF(A.DELIVERED_ACTIVITIES, 0),
        2
    ) AS CLICK_THROUGH_RATE_PCT,

    ROUND(
        100.0 * COALESCE(A.CONVERTED_ACTIVITIES, 0)
        / NULLIF(A.DELIVERED_ACTIVITIES, 0),
        2
    ) AS CONVERSION_RATE_PCT,

    ROUND(
        COALESCE(A.TOTAL_CONVERSION_VALUE, 0)
        / NULLIF(A.TOTAL_CAMPAIGN_COST, 0),
        2
    ) AS ROAS,

    CURRENT_TIMESTAMP() AS GOLD_CREATED_AT

FROM {{ ref('silver_crm_campaign_master') }} C

LEFT JOIN CAMPAIGN_ACTIVITY_METRICS A
    ON C.CAMPAIGN_ID = A.CAMPAIGN_ID