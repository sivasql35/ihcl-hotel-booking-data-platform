WITH CUSTOMER_METRICS AS (

    SELECT
        CUSTOMER_ID,

        COALESCE(CUSTOMER_SEGMENT, 'UNCLASSIFIED')
            AS CUSTOMER_SEGMENT,

        LOYALTY_TIER,
        CUSTOMER_STATUS,
        MARKETING_CONSENT,

        TOTAL_INTERACTIONS,
        AVG_SATISFACTION_SCORE,

        TOTAL_CAMPAIGN_ACTIVITIES,
        TOTAL_CAMPAIGN_OPENS,
        TOTAL_CAMPAIGN_CLICKS,
        TOTAL_CAMPAIGN_CONVERSIONS,

        TOTAL_CONVERSION_VALUE,
        TOTAL_CAMPAIGN_COST

    FROM {{ ref('gold_crm_customer_360') }}

)

SELECT
    CUSTOMER_SEGMENT,

    COUNT(DISTINCT CUSTOMER_ID)
        AS TOTAL_CUSTOMERS,

    COUNT_IF(CUSTOMER_STATUS = 'ACTIVE')
        AS ACTIVE_CUSTOMERS,

    COUNT_IF(CUSTOMER_STATUS <> 'ACTIVE')
        AS INACTIVE_CUSTOMERS,

    COUNT_IF(MARKETING_CONSENT = TRUE)
        AS MARKETING_OPTED_IN_CUSTOMERS,

    COUNT_IF(MARKETING_CONSENT = FALSE)
        AS MARKETING_OPTED_OUT_CUSTOMERS,

    COUNT(DISTINCT LOYALTY_TIER)
        AS DISTINCT_LOYALTY_TIERS,

    SUM(TOTAL_INTERACTIONS)
        AS TOTAL_INTERACTIONS,

    ROUND(AVG(TOTAL_INTERACTIONS), 2)
        AS AVG_INTERACTIONS_PER_CUSTOMER,

    ROUND(AVG(AVG_SATISFACTION_SCORE), 2)
        AS AVG_CUSTOMER_SATISFACTION,

    SUM(TOTAL_CAMPAIGN_ACTIVITIES)
        AS TOTAL_CAMPAIGN_ACTIVITIES,

    SUM(TOTAL_CAMPAIGN_OPENS)
        AS TOTAL_CAMPAIGN_OPENS,

    SUM(TOTAL_CAMPAIGN_CLICKS)
        AS TOTAL_CAMPAIGN_CLICKS,

    SUM(TOTAL_CAMPAIGN_CONVERSIONS)
        AS TOTAL_CAMPAIGN_CONVERSIONS,

    ROUND(
        100.0 * SUM(TOTAL_CAMPAIGN_CONVERSIONS)
        / NULLIF(SUM(TOTAL_CAMPAIGN_ACTIVITIES), 0),
        2
    ) AS CUSTOMER_CAMPAIGN_CONVERSION_RATE_PCT,

    SUM(TOTAL_CONVERSION_VALUE)
        AS TOTAL_CONVERSION_VALUE,

    SUM(TOTAL_CAMPAIGN_COST)
        AS TOTAL_CAMPAIGN_COST,

    ROUND(
        SUM(TOTAL_CONVERSION_VALUE)
        / NULLIF(SUM(TOTAL_CAMPAIGN_COST), 0),
        2
    ) AS SEGMENT_ROAS,

    CURRENT_TIMESTAMP() AS GOLD_CREATED_AT

FROM CUSTOMER_METRICS

GROUP BY CUSTOMER_SEGMENT
