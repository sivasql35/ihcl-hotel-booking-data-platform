
{{ config(materialized='table') }}

SELECT
    H.HOTEL_KEY,
    H.HOTEL,
    H.CITY,
    H.COUNTRY,

    COUNT(*) AS TOTAL_BOOKINGS,

    COUNT_IF(F.IS_CANCELED = 1) AS CANCELED_BOOKINGS,

    COUNT_IF(F.IS_CANCELED = 0) AS NOT_CANCELED_BOOKINGS,

    ROUND(
        COUNT_IF(F.IS_CANCELED = 1) * 100.0
        / NULLIF(COUNT(*), 0),
        2
    ) AS CANCELLATION_RATE_PCT,

    ROUND(AVG(F.ADR), 2) AS AVG_ADR,

    ROUND(AVG(F.TOTAL_GUESTS), 2) AS AVG_GUESTS_PER_BOOKING,

    SUM(F.TOTAL_STAY_NIGHTS) AS TOTAL_ROOM_NIGHTS,

    CURRENT_TIMESTAMP()::TIMESTAMP_NTZ AS LAST_REFRESHED_AT

FROM {{ ref('fact_bookings') }} F

JOIN {{ ref('dim_hotel') }} H
    ON F.HOTEL_KEY = H.HOTEL_KEY

GROUP BY
    H.HOTEL_KEY,
    H.HOTEL,
    H.CITY,
    H.COUNTRY