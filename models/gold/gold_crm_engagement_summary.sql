WITH INTERACTION_SUMMARY AS (

    SELECT
        CUSTOMER_ID,

        COUNT(INTERACTION_ID) AS TOTAL_INTERACTIONS,

        COUNT_IF(INTERACTION_STATUS = 'CLOSED')
            AS CLOSED_INTERACTIONS,

        COUNT_IF(INTERACTION_STATUS = 'OPEN')
            AS OPEN_INTERACTIONS,

        COUNT_IF(INTERACTION_STATUS = 'PENDING')
            AS PENDING_INTERACTIONS,

        COUNT_IF(PRIORITY = 'HIGH')
            AS HIGH_PRIORITY_INTERACTIONS,

        COUNT_IF(PRIORITY = 'MEDIUM')
            AS MEDIUM_PRIORITY_INTERACTIONS,

        COUNT_IF(PRIORITY = 'LOW')
            AS LOW_PRIORITY_INTERACTIONS,

        AVG(RESOLUTION_TIME_HOURS)
            AS AVG_RESOLUTION_TIME_HOURS,

        AVG(CUSTOMER_SATISFACTION_SCORE)
            AS AVG_SATISFACTION_SCORE,

        MAX(INTERACTION_DATE)
            AS LAST_INTERACTION_DATE,

        MIN(INTERACTION_DATE)
            AS FIRST_INTERACTION_DATE

    FROM {{ ref('silver_crm_interactions') }}

    GROUP BY CUSTOMER_ID

),

CHANNEL_SUMMARY AS (

    SELECT
        CUSTOMER_ID,

        COUNT_IF(CHANNEL = 'EMAIL') AS EMAIL_INTERACTIONS,

        COUNT_IF(CHANNEL = 'PHONE') AS PHONE_INTERACTIONS,

        COUNT_IF(CHANNEL = 'CHAT') AS CHAT_INTERACTIONS,

        COUNT_IF(CHANNEL = 'WEBSITE') AS WEBSITE_INTERACTIONS

    FROM {{ ref('silver_crm_interactions') }}

    GROUP BY CUSTOMER_ID

),

CUSTOMER_BASE AS (

    SELECT
        CUSTOMER_ID,
        FIRST_NAME,
        LAST_NAME,
        CUSTOMER_SEGMENT,
        LOYALTY_TIER,
        CUSTOMER_STATUS,
        REGISTRATION_DATE

    FROM {{ ref('silver_crm_customers') }}

)

SELECT
    C.CUSTOMER_ID,
    C.FIRST_NAME,
    C.LAST_NAME,
    C.CUSTOMER_SEGMENT,
    C.LOYALTY_TIER,
    C.CUSTOMER_STATUS,
    C.REGISTRATION_DATE,

    COALESCE(I.TOTAL_INTERACTIONS, 0)
        AS TOTAL_INTERACTIONS,

    COALESCE(I.CLOSED_INTERACTIONS, 0)
        AS CLOSED_INTERACTIONS,

    COALESCE(I.OPEN_INTERACTIONS, 0)
        AS OPEN_INTERACTIONS,

    COALESCE(I.PENDING_INTERACTIONS, 0)
        AS PENDING_INTERACTIONS,

    COALESCE(I.HIGH_PRIORITY_INTERACTIONS, 0)
        AS HIGH_PRIORITY_INTERACTIONS,

    COALESCE(I.MEDIUM_PRIORITY_INTERACTIONS, 0)
        AS MEDIUM_PRIORITY_INTERACTIONS,

    COALESCE(I.LOW_PRIORITY_INTERACTIONS, 0)
        AS LOW_PRIORITY_INTERACTIONS,

    I.AVG_RESOLUTION_TIME_HOURS,
    I.AVG_SATISFACTION_SCORE,
    I.FIRST_INTERACTION_DATE,
    I.LAST_INTERACTION_DATE,

    COALESCE(CH.EMAIL_INTERACTIONS, 0)
        AS EMAIL_INTERACTIONS,

    COALESCE(CH.PHONE_INTERACTIONS, 0)
        AS PHONE_INTERACTIONS,

    COALESCE(CH.CHAT_INTERACTIONS, 0)
        AS CHAT_INTERACTIONS,

    COALESCE(CH.WEBSITE_INTERACTIONS, 0)
        AS WEBSITE_INTERACTIONS,

    CURRENT_TIMESTAMP() AS GOLD_CREATED_AT

FROM CUSTOMER_BASE C

LEFT JOIN INTERACTION_SUMMARY I
    ON C.CUSTOMER_ID = I.CUSTOMER_ID

LEFT JOIN CHANNEL_SUMMARY CH
    ON C.CUSTOMER_ID = CH.CUSTOMER_ID