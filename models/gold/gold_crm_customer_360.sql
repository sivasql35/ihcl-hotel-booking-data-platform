WITH CUSTOMER_PROFILE AS (

    SELECT
        CUSTOMER_ID,
        FIRST_NAME,
        LAST_NAME,
        EMAIL,
        PHONE,
        DATE_OF_BIRTH,
        GENDER,
        CITY,
        STATE,
        COUNTRY,
        REGISTRATION_DATE,
        CUSTOMER_SEGMENT,
        LOYALTY_TIER,
        PREFERRED_CHANNEL,
        MARKETING_CONSENT,
        CUSTOMER_STATUS
    FROM {{ ref('silver_crm_customers') }}

),

INTERACTION_METRICS AS (

    SELECT
        CUSTOMER_ID,
        COUNT(INTERACTION_ID) AS TOTAL_INTERACTIONS,
        MAX(INTERACTION_DATE) AS LAST_INTERACTION_DATE,
        AVG(CUSTOMER_SATISFACTION_SCORE)
            AS AVG_SATISFACTION_SCORE,
        SUM(RESOLUTION_TIME_HOURS)
            AS TOTAL_RESOLUTION_HOURS
    FROM {{ ref('silver_crm_interactions') }}
    GROUP BY CUSTOMER_ID

),

CAMPAIGN_METRICS AS (

    SELECT
        CUSTOMER_ID,
        COUNT(CAMPAIGN_ACTIVITY_ID)
            AS TOTAL_CAMPAIGN_ACTIVITIES,

        COUNT(DISTINCT CAMPAIGN_ID)
            AS DISTINCT_CAMPAIGNS,

        COUNT_IF(OPEN_DATE IS NOT NULL)
            AS TOTAL_CAMPAIGN_OPENS,

        COUNT_IF(CLICK_DATE IS NOT NULL)
            AS TOTAL_CAMPAIGN_CLICKS,

        COUNT_IF(CONVERSION_DATE IS NOT NULL)
            AS TOTAL_CAMPAIGN_CONVERSIONS,

        SUM(CONVERSION_VALUE)
            AS TOTAL_CONVERSION_VALUE,

        SUM(CAMPAIGN_COST)
            AS TOTAL_CAMPAIGN_COST,

        MAX(SENT_DATE)
            AS LAST_CAMPAIGN_SENT_DATE

    FROM {{ ref('silver_crm_campaign_activity') }}
    GROUP BY CUSTOMER_ID

)

SELECT
    C.CUSTOMER_ID,
    C.FIRST_NAME,
    C.LAST_NAME,
    TRIM(C.FIRST_NAME || ' ' || C.LAST_NAME)
        AS CUSTOMER_FULL_NAME,

    C.EMAIL,
    C.PHONE,
    C.DATE_OF_BIRTH,
    C.GENDER,
    C.CITY,
    C.STATE,
    C.COUNTRY,
    C.REGISTRATION_DATE,
    C.CUSTOMER_SEGMENT,
    C.LOYALTY_TIER,
    C.PREFERRED_CHANNEL,
    C.MARKETING_CONSENT,
    C.CUSTOMER_STATUS,

    COALESCE(I.TOTAL_INTERACTIONS, 0)
        AS TOTAL_INTERACTIONS,

    I.LAST_INTERACTION_DATE,
    I.AVG_SATISFACTION_SCORE,

    COALESCE(I.TOTAL_RESOLUTION_HOURS, 0)
        AS TOTAL_RESOLUTION_HOURS,

    COALESCE(A.TOTAL_CAMPAIGN_ACTIVITIES, 0)
        AS TOTAL_CAMPAIGN_ACTIVITIES,

    COALESCE(A.DISTINCT_CAMPAIGNS, 0)
        AS DISTINCT_CAMPAIGNS,

    COALESCE(A.TOTAL_CAMPAIGN_OPENS, 0)
        AS TOTAL_CAMPAIGN_OPENS,

    COALESCE(A.TOTAL_CAMPAIGN_CLICKS, 0)
        AS TOTAL_CAMPAIGN_CLICKS,

    COALESCE(A.TOTAL_CAMPAIGN_CONVERSIONS, 0)
        AS TOTAL_CAMPAIGN_CONVERSIONS,

    COALESCE(A.TOTAL_CONVERSION_VALUE, 0)
        AS TOTAL_CONVERSION_VALUE,

    COALESCE(A.TOTAL_CAMPAIGN_COST, 0)
        AS TOTAL_CAMPAIGN_COST,

    A.LAST_CAMPAIGN_SENT_DATE,

    CURRENT_TIMESTAMP() AS GOLD_CREATED_AT

FROM CUSTOMER_PROFILE C

LEFT JOIN INTERACTION_METRICS I
    ON C.CUSTOMER_ID = I.CUSTOMER_ID

LEFT JOIN CAMPAIGN_METRICS A
    ON C.CUSTOMER_ID = A.CUSTOMER_ID