WITH SOURCE_DATA AS (

    SELECT
        NULLIF(TRIM(CAMPAIGN_ACTIVITY_ID), '')
            AS CAMPAIGN_ACTIVITY_ID,

        NULLIF(TRIM(CAMPAIGN_ID), '') AS CAMPAIGN_ID,

        NULLIF(TRIM(CUSTOMER_ID), '') AS CUSTOMER_ID,

        UPPER(TRIM(CHANNEL)) AS CHANNEL,

        TRY_TO_DATE(SENT_DATE) AS SENT_DATE,

        UPPER(TRIM(DELIVERY_STATUS)) AS DELIVERY_STATUS,

        TRY_TO_DATE(OPEN_DATE) AS OPEN_DATE,

        TRY_TO_DATE(CLICK_DATE) AS CLICK_DATE,

        TRY_TO_DATE(CONVERSION_DATE) AS CONVERSION_DATE,

        UPPER(TRIM(RESPONSE_STATUS)) AS RESPONSE_STATUS,

        TRY_TO_DECIMAL(CONVERSION_VALUE, 18, 2)
            AS CONVERSION_VALUE,

        TRY_TO_DECIMAL(CAMPAIGN_COST, 18, 2)
            AS CAMPAIGN_COST,

        TRY_TO_TIMESTAMP_NTZ(CREATED_AT) AS CREATED_AT,

        SOURCE_FILE_NAME,
        FILE_ROW_NUMBER,
        FILE_LAST_MODIFIED,
        INGESTION_TIMESTAMP

    FROM {{ source('bronze', 'CRM_CAMPAIGN_ACTIVITY') }}

),

DEDUPLICATED AS (

    SELECT *
    FROM SOURCE_DATA

    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY CAMPAIGN_ACTIVITY_ID
        ORDER BY
            INGESTION_TIMESTAMP DESC NULLS LAST,
            FILE_LAST_MODIFIED DESC NULLS LAST,
            FILE_ROW_NUMBER DESC NULLS LAST
    ) = 1

)

SELECT *
FROM DEDUPLICATED
WHERE CAMPAIGN_ACTIVITY_ID IS NOT NULL
