
{{ config(materialized='table') }}

WITH SOURCE_DATA AS (

    SELECT
        TRIM(CUSTOMER_ID) AS CUSTOMER_ID,
        INITCAP(TRIM(FIRST_NAME)) AS FIRST_NAME,
        INITCAP(TRIM(LAST_NAME)) AS LAST_NAME,
        LOWER(TRIM(EMAIL)) AS EMAIL,
        TRIM(PHONE) AS PHONE,

        TRY_TO_DATE(DATE_OF_BIRTH) AS DATE_OF_BIRTH,
        UPPER(TRIM(GENDER)) AS GENDER,

        INITCAP(TRIM(CITY)) AS CITY,
        INITCAP(TRIM(STATE)) AS STATE,
        UPPER(TRIM(COUNTRY)) AS COUNTRY,

        TRY_TO_DATE(REGISTRATION_DATE) AS REGISTRATION_DATE,

        UPPER(TRIM(CUSTOMER_SEGMENT)) AS CUSTOMER_SEGMENT,
        UPPER(TRIM(LOYALTY_TIER)) AS LOYALTY_TIER,
        UPPER(TRIM(PREFERRED_CHANNEL)) AS PREFERRED_CHANNEL,

        TRY_TO_BOOLEAN(MARKETING_CONSENT) AS MARKETING_CONSENT,
        UPPER(TRIM(CUSTOMER_STATUS)) AS CUSTOMER_STATUS,

        TRY_TO_TIMESTAMP_NTZ(CREATED_AT) AS CREATED_AT,
        TRY_TO_TIMESTAMP_NTZ(UPDATED_AT) AS UPDATED_AT,

        SOURCE_FILE_NAME,
        FILE_ROW_NUMBER,
        FILE_LAST_MODIFIED,
        INGESTION_TIMESTAMP

    FROM {{ source('bronze', 'CRM_CUSTOMERS') }}

),

DEDUPLICATED AS (

    SELECT *
    FROM SOURCE_DATA

    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY CUSTOMER_ID
        ORDER BY
            UPDATED_AT DESC NULLS LAST,
            INGESTION_TIMESTAMP DESC
    ) = 1

)

SELECT *
FROM DEDUPLICATED
WHERE CUSTOMER_ID IS NOT NULL