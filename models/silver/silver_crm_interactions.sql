WITH SOURCE_DATA AS (

    SELECT
        NULLIF(TRIM(INTERACTION_ID), '') AS INTERACTION_ID,
        NULLIF(TRIM(CUSTOMER_ID), '') AS CUSTOMER_ID,

        TRY_TO_TIMESTAMP_NTZ(INTERACTION_DATE)
            AS INTERACTION_DATE,

        UPPER(TRIM(INTERACTION_TYPE)) AS INTERACTION_TYPE,
        UPPER(TRIM(CHANNEL)) AS CHANNEL,

        NULLIF(TRIM(SUBJECT), '') AS SUBJECT,
        NULLIF(TRIM(DESCRIPTION), '') AS DESCRIPTION,

        INITCAP(TRIM(HOTEL)) AS HOTEL,
        INITCAP(TRIM(CITY)) AS CITY,

        UPPER(TRIM(PRIORITY)) AS PRIORITY,
        UPPER(TRIM(INTERACTION_STATUS)) AS INTERACTION_STATUS,

        TRY_TO_NUMBER(RESOLUTION_TIME_HOURS)
            AS RESOLUTION_TIME_HOURS,

        TRY_TO_NUMBER(CUSTOMER_SATISFACTION_SCORE)
            AS CUSTOMER_SATISFACTION_SCORE,

        TRY_TO_TIMESTAMP_NTZ(CREATED_AT) AS CREATED_AT,

        SOURCE_FILE_NAME,
        FILE_ROW_NUMBER,
        FILE_LAST_MODIFIED,
        INGESTION_TIMESTAMP

    FROM {{ source('bronze', 'CRM_INTERACTIONS') }}

),

DEDUPLICATED AS (

    SELECT *
    FROM SOURCE_DATA

    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY INTERACTION_ID
        ORDER BY
            INGESTION_TIMESTAMP DESC NULLS LAST,
            FILE_LAST_MODIFIED DESC NULLS LAST,
            FILE_ROW_NUMBER DESC NULLS LAST
    ) = 1

)

SELECT *
FROM DEDUPLICATED
WHERE INTERACTION_ID IS NOT NULL
