WITH SOURCE_DATA AS (

    SELECT
        NULLIF(TRIM(CAMPAIGN_ID), '') AS CAMPAIGN_ID,

        INITCAP(TRIM(CAMPAIGN_NAME)) AS CAMPAIGN_NAME,

        UPPER(TRIM(CAMPAIGN_TYPE)) AS CAMPAIGN_TYPE,

        UPPER(TRIM(CHANNEL)) AS CHANNEL,

        INITCAP(TRIM(TARGET_AUDIENCE)) AS TARGET_AUDIENCE,

        TRY_TO_DATE(CAMPAIGN_START_DATE)
            AS CAMPAIGN_START_DATE,

        TRY_TO_DATE(CAMPAIGN_END_DATE)
            AS CAMPAIGN_END_DATE,

        TRY_TO_DECIMAL(CAMPAIGN_BUDGET, 18, 2)
            AS CAMPAIGN_BUDGET,

        UPPER(TRIM(CAMPAIGN_STATUS))
            AS CAMPAIGN_STATUS,

        SOURCE_FILE_NAME,
        FILE_ROW_NUMBER,
        FILE_LAST_MODIFIED,
        INGESTION_TIMESTAMP

    FROM {{ source('bronze', 'CRM_CAMPAIGN_MASTER') }}

),

DEDUPLICATED AS (

    SELECT *
    FROM SOURCE_DATA

    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY CAMPAIGN_ID
        ORDER BY
            INGESTION_TIMESTAMP DESC NULLS LAST,
            FILE_LAST_MODIFIED DESC NULLS LAST,
            FILE_ROW_NUMBER DESC NULLS LAST
    ) = 1

)

SELECT *
FROM DEDUPLICATED
WHERE CAMPAIGN_ID IS NOT NULL
